export const listOrgs = async (req, res) => {
  const { status, plan, page = 1, limit = 20 } = req.query;
  const query = {};
  if (status) query.status = status;
  if (plan) query.plan = plan;

  const orgs = await Organisation.find(query)
    .sort({ createdAt: -1 })
    .skip((page - 1) * limit)
    .limit(Number(limit))
    .lean();

  const total = await Organisation.countDocuments(query);

  // Get user counts
  const orgIds = orgs.map((org) => org._id);
  const userCounts = await User.aggregate([
    { $match: { orgId: { $in: orgIds } } },
    { $group: { _id: '$orgId', count: { $sum: 1 } } }
  ]);
  
  const countMap = Object.fromEntries(userCounts.map(u => [u._id.toString(), u.count]));

  const data = orgs.map(org => ({
    ...org,
    userCount: countMap[org._id.toString()] || 0
  }));

  res.status(200).json(new ApiResponse(200, { data, total, page: Number(page), limit: Number(limit) }, "Organisations fetched successfully"));
};

export const createOrg = async (req, res) => {
  const { name, plan } = req.body;
  if (!name) throw new ApiError(400, "Name is required");

  // Slug auto-generated by Mongoose pre-validate hook
  const org = await Organisation.create({
    name,
    plan: plan || 'trial',
    status: 'pending',
    createdBy: req.user._id
  });

  logAudit(req, 'org.created', { type: 'Organisation', id: org._id }, { name, plan });

  res.status(201).json(new ApiResponse(201, org, "Organisation created successfully"));
};

export const getOrgDetail = async (req, res) => {
  const { orgId } = req.params;
  const org = await Organisation.findById(orgId).lean();
  if (!org) throw new ApiError(404, "Organisation not found");

  const users = await User.find({ orgId }).select("-password -refreshToken").lean();
  const apiKeys = await ApiKey.find({ orgId }).lean();
  
  // Current month stats
  const startOfMonth = new Date();
  startOfMonth.setDate(1);
  startOfMonth.setHours(0, 0, 0, 0);

  const [eventsCount, incidentsCount, investigationsCount] = await Promise.all([
    Event.countDocuments({ orgId, createdAt: { $gte: startOfMonth } }),
    Incident.countDocuments({ orgId, createdAt: { $gte: startOfMonth } }),
    Investigation.countDocuments({ orgId, createdAt: { $gte: startOfMonth } })
  ]);

  const detail = {
    ...org,
    users,
    apiKeys: apiKeys.map(key => {
      const { keyHash, ...safeKey } = key;
      return safeKey;
    }),
    stats: {
      eventsThisMonth: eventsCount,
      incidentsThisMonth: incidentsCount,
      investigationsThisMonth: investigationsCount
    }
  };

  res.status(200).json(new ApiResponse(200, detail, "Organisation detail fetched successfully"));
};

export const updateOrgStatus = async (req, res) => {
  const { orgId } = req.params;
  const { status } = req.body;

  if (!['active', 'suspended', 'pending'].includes(status)) {
    throw new ApiError(400, "Invalid status");
  }

  const org = await Organisation.findByIdAndUpdate(orgId, { status }, { new: true }).lean();
  if (!org) throw new ApiError(404, "Organisation not found");

  const action = status === 'suspended' ? 'org.suspended' : 'org.activated';
  logAudit(req, action, { type: 'Organisation', id: org._id });

  res.status(200).json(new ApiResponse(200, org, "Organisation status updated successfully"));
};

export const updateOrgConfig = async (req, res) => {
  const { orgId } = req.params;
  const { config } = req.body;

  if (!config || typeof config !== 'object') {
    throw new ApiError(400, "Config object is required");
  }

  const org = await Organisation.findById(orgId);
  if (!org) throw new ApiError(404, "Organisation not found");

  // Deep merge config manually to prevent clearing other fields
  org.config = {
    ...org.config,
    ...config,
    usageLimits: {
      ...(org.config?.usageLimits || {}),
      ...(config.usageLimits || {})
    }
  };

  await org.save();

  logAudit(req, 'org.config_updated', { type: 'Organisation', id: org._id }, { updatedFields: Object.keys(config) });

  res.status(200).json(new ApiResponse(200, org, "Organisation config updated successfully"));
};

export const inviteOrgAdmin = async (req, res) => {
  const { orgId } = req.params;
  const { email } = req.body;

  if (!email) throw new ApiError(400, "Email is required");

  const existingUser = await User.findOne({ email });
  if (existingUser) {
    throw new ApiError(400, "A user with this email already exists");
  }

  const org = await Organisation.findById(orgId);
  if (!org) throw new ApiError(404, "Organisation not found");

  // Create a placeholder user
  const newUser = await User.create({
    username: email.split('@')[0] + '_' + Math.random().toString(36).substring(2, 6),
    email,
    password: crypto.randomBytes(32).toString('hex'), // Random impossible password
    role: 'org_admin',
    orgId,
    isActive: false,
    invitedBy: req.user._id
  });

  const { unHashedToken } = newUser.generateInviteToken();
  await newUser.save();

  const inviteUrl = `${process.env.APP_URL || 'http://localhost:3000'}/invite/accept?token=${unHashedToken}`;
  const orgName = org.name;

  try {
    await sendEmail({
      email,
      subject: `You've been invited to Sentinel — ${orgName}`,
      mailgenContent: inviteMailgenContent(email, orgName, inviteUrl),
    });
  } catch (error) {
    console.error("Failed to send invite email:", error);
    // Continue even if email fails in development, but we should log it
  }

  // Return the token in development so it can be tested
  res.status(201).json(new ApiResponse(201, {
    message: "User invited successfully",
    inviteLink: process.env.NODE_ENV !== 'production' ? inviteUrl : undefined
  }, "Invitation sent"));
};

export const resendInvite = async (req, res) => {
  const { orgId, userId } = req.params;

  const user = await User.findOne({ _id: userId, orgId });
  if (!user) throw new ApiError(404, "User not found in this organisation");
  if (user.isActive) throw new ApiError(400, "User is already active");

  const { unHashedToken } = user.generateInviteToken();
  await user.save();

  const org = await Organisation.findById(orgId).lean();
  const inviteUrl = `${process.env.APP_URL || 'http://localhost:3000'}/invite/accept?token=${unHashedToken}`;

  try {
    await sendEmail({
      email: user.email,
      subject: `You've been invited to Sentinel — ${org.name}`,
      mailgenContent: inviteMailgenContent(user.email, org.name, inviteUrl),
    });
  } catch (error) {
    console.error("Failed to resend invite email:", error);
  }

  res.status(200).json(new ApiResponse(200, {
    message: "Invite resent successfully",
    inviteLink: process.env.NODE_ENV !== 'production' ? inviteUrl : undefined
  }, "Invitation resent"));
};

